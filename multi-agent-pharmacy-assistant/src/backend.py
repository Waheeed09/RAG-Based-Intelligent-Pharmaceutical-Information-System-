def register_drug_names(pdf_docs, csv_path):
    names = set()
    for d in pdf_docs:                       # "17. Augmentin Syrup" -> augmentin
        m = re.match(r"\d{1,3}\.\s+([A-Za-z\-]+)", d.page_content)
        if m: names.add(m.group(1).lower())
    df = pd.read_csv(csv_path, dtype=str, keep_default_na=False)
    for col in ("Trade Name", "Active Ingredient"):
        for v in df[col]:
            for w in re.findall(r"[a-z]+", v.lower()):
                names.add(w)
    DRUG_TERMS.update(w for w in names if len(w) >= 4 and w not in GENERIC_WORDS)

