def data_retrieval_agent(state: AgentState):
    print("-> [Agent 1: Retrieval] Gathering data from VectorDB and External APIs...")
    task = state["task"]
    last_q = state.get("last_question", "")
    last_a = state.get("last_answer", "")
    last_pool = state.get("last_pool") or []
    last_shown = state.get("last_shown") or []
    state.update({"mode": "qa", "docs": [], "context": "", "pool": [], "shown": []})

    try:
        info = understand(task)                      # Step 3b: symptoms / child / red flags / cheapest-priciest
        state["reco"] = info
        rank = info["rank"]
        if GREETING.match(task):
            state["mode"] = "smalltalk"
        elif SUMMARIZE.search(task) and not info["drug_named"]:
            if last_shown:                           # the last answer was a list of drugs -> keep only 2
                state["mode"] = "summarize_list"
                state["shown"], state["pool"] = last_shown, last_pool
                state["retrieved_data"] = "PREVIOUS LIST:\n" + items_context(last_shown)
            else:                                    # the last answer was plain text -> summarize the text
                has_answer = bool(last_a.strip()) and last_a not in FIXED_REPLIES
                state["mode"] = "summarize" if has_answer else "nothing"
                state["context"] = last_a
                state["retrieved_data"] = f"PREVIOUS ANSWER:\n{last_a}"
        elif info["self_harm"] or info["red_flag"]:
            state["mode"] = "recommend"              # safety message, no drug is suggested
            state["retrieved_data"] = ""
        elif rank and not info["symptoms"] and not info["drug_named"]:
            # "get the cheapest" / "and the most expensive?" -> use the previous list (chat history)
            if last_pool:
                state["mode"] = "rank"
                state["pool"] = last_pool
                state["shown"] = [pick_by_price(last_pool, rank)]
                state["retrieved_data"] = "PREVIOUS LIST:\n" + items_context(last_pool)
            else:
                state["mode"] = "nothing_to_rank"
        elif info["symptoms"] and not info["drug_named"]:
            # "I have a cold, recommend something" (or "cheapest medicine for a headache")
            pool = build_items(info, top_n=6 if rank else 3)
            state["mode"] = "recommend"
            state["pool"] = pool
            state["shown"] = [pick_by_price(pool, rank)] if (rank and pool) else pool
            state["retrieved_data"] = "RECOMMENDATION CONTEXT:\n" + items_context(pool)
            state["context"] = state["retrieved_data"]
        else:
            query = expand_query(task, last_q)
            docs, matched = retrieve_docs(state["vector_store"], query)
            local_context = "\n\n".join(d.page_content for d in docs)

            external = "Not requested."
            wants_fda = "fda" in task.lower()
            if wants_fda:
                external = fetch_fda_label(task + "\n" + local_context)
                if any(n in task.lower() for n in FDA_NAMES):
                    matched = True

            state["docs"] = docs
            state["context"] = local_context + (f"\n\n{external}" if wants_fda else "")
            state["retrieved_data"] = f"LOCAL CONTEXT:\n{local_context}\n\nEXTERNAL API CONTEXT:\n{external}"
            if not matched:
                state["mode"] = "no_info"   # nothing in the data is about this question
    except Exception as e:
        state["mode"] = "no_info"
        state["retrieved_data"] = f"Retrieval error: {type(e).__name__}: {e}"

    state["log"].append(f"Data Retrieval Agent completed (mode: {state['mode']}).")
    return state

