def run_conversation_tests(vector_store):
    # Multi-turn test: the system must understand the chat history.
    print("\n" + "=" * 50)
    print("💬 Conversation (chat history) tests")
    print("=" * 50)
    chat = ChatSession(build_workflow(), vector_store)
    checks = []

    def turn(msg):
        print(f"\nUser: {msg}")
        out = chat.ask(msg)
        print(f"Assistant:\n{out}")
        return out

    a1 = turn("I have a cold, recommend me a medicine")
    checks.append(("recommendation lists drugs", "Congestal Tabs" in a1))

    a2 = turn("summarize")
    n_drugs = len(re.findall(r"^\d+\. ", a2, flags=re.M))
    checks.append(("'summarize' keeps exactly 2 drugs", n_drugs == 2))

    cheapest = pick_by_price(chat.pool, "cheapest")["name"]
    priciest = pick_by_price(chat.pool, "priciest")["name"]
    a3 = turn("get the cheapest")
    checks.append((f"'get the cheapest' picks {cheapest} from the previous list", cheapest in a3 and "cheapest" in a3))

    a4 = turn("and the most expensive one?")
    checks.append((f"'most expensive' picks {priciest} from the previous list", priciest in a4 and "most expensive" in a4))

    a5 = turn("I have a headache, give me the cheapest medicine")
    checks.append(("symptom + cheapest in one message", "headache" in a5.lower() and "cheapest" in a5))

    chat.reset()
    a6 = turn("get the cheapest")
    checks.append(("'cheapest' with no history asks for a symptom first", a6 == NOTHING_TO_RANK))

    print("\n" + "-" * 50)
    for name, ok in checks:
        print(f"{'PASS' if ok else 'FAIL'}  {name}")
    print(f"Conversation tests: {sum(ok for _, ok in checks)}/{len(checks)}")


