# ---------- 3) Reading the two data files into structured records ----------
GUIDE = []        # one dict per drug of the PDF guide
INVENTORY = []    # one dict per drug of the CSV inventory
BRAND_WORDS = set()   # names/ingredients that show the user is asking about a specific drug

NAME_TAIL = re.compile(r"(?:Chew\s+)?(?:Suppositories|Elixir|Syrup|Flu Day|Tabs|Caps|Drops|Gel|Cream|Ointment|Liquid|Sachets|Lozenges|Caplets|Wash|Capsules|Tablets|Inhalant|Suspension)", re.I)

def parse_guide_chunk(chunk):
    # "17. Augmentin Syrup\n457\nAmoxicillin + Clavulanate\n85 EGP <indications>\n<dosage>\n<pediatric>" -> dict
    lines = [l.strip() for l in chunk.splitlines() if l.strip()]
    pi = next((i for i, l in enumerate(lines) if re.search(r"\d+(?:\.\d+)?\s*EGP", l)), None)
    if pi is None:
        return None
    head, m = lines[:pi], re.search(r"(\d+(?:\.\d+)?)\s*EGP\s*(.*)", lines[pi])
    name, k = re.sub(r"^\d{1,3}\.\s*", "", head[0]), 1
    while k < len(head) and (re.fullmatch(r"\d+", head[k]) or NAME_TAIL.fullmatch(head[k]) or name.endswith(("+", "-"))):
        name, k = (name + head[k] if name.endswith("-") else name + " " + head[k]), k + 1      # continuation of the product name
    rest = re.sub(r"\s+\.", ".", " ".join([m.group(2)] + lines[pi + 1:]))
    segs = [s.strip() for s in re.split(r"(?<!e\.g)\.(?=\s|$)", rest) if s.strip()]
    if len(segs) != 3:                      # unexpected layout -> keep everything in 'indication'
        segs = [rest, "", ""]
    return {"name": name, "ingredient": " ".join(head[k:]), "price": m.group(1),
            "indication": segs[0], "dose": segs[1], "pediatric": segs[2], "text": chunk}

def child_ok(ped):
    # Is the pediatric note of the guide good news for a child?  (kept strict on purpose)
    p = ped.lower()
    if re.search(r"contraindicated|adults?\b|not (?:for|suitable|recommended)|under \d|age \d+\+|above 1\d|strict|caution|supervision|monitor|per md|per pediatrician|specialist|short-term|very short", p):
        return False
    return bool(re.search(r"safe|essential|extremely|syrup|drops|ages? \d{1,2} to \d{1,2}|above \d\b|suitable above \d\b", p))

def build_recommender(pdf_docs, csv_path):
    GUIDE.clear(); INVENTORY.clear(); BRAND_WORDS.clear()
    for d in pdf_docs:
        r = parse_guide_chunk(d.page_content)
        if r: GUIDE.append(r)
    df = pd.read_csv(csv_path, dtype=str, keep_default_na=False)
    INVENTORY.extend(df.to_dict("records"))
    # which words in a user message mean "a specific drug" (brand names + long ingredient names)
    for r in GUIDE:
        m = re.match(r"[A-Za-z]{4,}", r["name"])
        if m: BRAND_WORDS.add(m.group(0).lower())
    for r in INVENTORY:
        m = re.match(r"[A-Za-z]{4,}", r["Trade Name"].strip())
        if m: BRAND_WORDS.add(m.group(0).lower())
    for src in [r["ingredient"] for r in GUIDE] + [r["Active Ingredient"] for r in INVENTORY]:
        for w in re.findall(r"[A-Za-z]{7,}", src.lower()):
            if w not in GENERIC_WORDS and w not in {"multivitamins", "extracts", "pediatric", "solution", "chloride", "fumarate", "potassium", "methylsulfate", "dihydrochloride", "propionate", "hydrochloride", "bromide", "sulfate", "enzymes", "minerals", "complex", "digestive", "antispasmodic", "botanical", "peroxide"}:
                BRAND_WORDS.add(w)
    BRAND_WORDS.update({"paracetamol", "ibuprofen", "diclofenac"})
    print(f"Recommender ready: {len(GUIDE)} guide drugs, {len(INVENTORY)} inventory drugs, {len(SYMPTOMS)} symptoms understood.")

# ---------- 4) Understanding the message ----------
def mentions_specific_drug(norm_text):
    return bool(set(re.findall(r"[a-z]{4,}", norm_text)) & BRAND_WORDS)

def understand(task):
    # -> dict(symptoms, child, red_flag, self_harm, drug_named, rank)
    norm = normalize(task)
    found = [key for key, s in SYMPTOMS.items() if s["pats"].search(norm)]
    # "dry cough"/"chesty cough" are more specific than plain "cough"
    if "cough" in found and ("cough_dry" in found or "cough_wet" in found):
        found.remove("cough")
    if "migraine" in found and "headache" in found:
        found.remove("headache")
    if "sinus" in found and "stuffy_nose" in found:
        found.remove("stuffy_nose")
    if "pain" in found and set(found) & {"stomach_cramps", "toothache", "muscle_joint", "ear", "sore_throat", "headache", "migraine", "dysmenorrhea", "nerve_pain", "dry_eye"}:
        found.remove("pain")                           # a more specific pain was named -> drop the generic one
    if "uti" in found and "infection" in found:
        found.remove("infection")
    rank = "priciest" if PRICIEST.search(task) else ("cheapest" if CHEAPEST.search(task) else None)
    return {"symptoms": found, "child": bool(CHILD_WORDS.search(norm)),
            "red_flag": bool(RED_FLAGS.search(norm)), "self_harm": bool(SELF_HARM.search(norm)),
            "drug_named": mentions_specific_drug(norm), "rank": rank}

# ---------- 5) Choosing drugs ----------
RX_INGREDIENTS = re.compile(r"amoxicillin|clavulan|azithromycin|ciproflox|levoflox|cefotax|ceftriax|clindamycin|metronidazole|doxycycline|erythromycin|sulfamethoxazole|flucloxacillin|ketorolac|bisoprolol|captopril|amlodipine|indapamide|sitagliptin|metformin|glimepiride|atorvastatin|rosuvastatin|levothyroxine|clopidogrel|warfarin|spironolactone|carbamazepine|valproate|pregabalin|zolmitriptan|flupentixol|estradiol|desogestrel|tobramycin|betamethasone|valsartan|nifuroxazide.*zzz", re.I)

def _score(text, terms):
    t, s = text.lower(), 0
    for rx, w in terms:
        if re.search(rx, t): s += w
    return s

def _first(name):
    m = re.search(r"[A-Za-z]+", name)
    return m.group(0).lower() if m else ""

def _stock_info(guide_name):
    first = _first(guide_name)
    for r in INVENTORY:
        if _first(r["Trade Name"]) == first:
            return r
    return None

def recommend(info, top_n=3):
    keys, child = info["symptoms"], info["child"]
    guide_hits, inv_hits = [], []
    for g in GUIDE:
        sc = sum(_score(g["indication"] + " " + g["name"], SYMPTOMS[k]["terms"]) for k in keys)
        if sc <= 0: continue
        ok = child_ok(g["pediatric"])
        if child and not ok: continue                       # never suggest a non-pediatric drug for a child
        inv = _stock_info(g["name"])
        rx = (inv["Prescription Required"].strip().lower() == "yes") if inv else bool(RX_INGREDIENTS.search(g["ingredient"]))
        in_stock = 1 if (inv and inv["Availability Status"] != "Out of Stock") else 0
        adj = sc + (1 if ok else 0)
        if not child and re.search(r"syrup|drops|suspension|water|suppositor", g["name"].lower()):
            adj -= 1.5                                       # adult asking -> kids' forms come after the adult forms
        guide_hits.append((adj, -int(rx), in_stock, -len(guide_hits), g, inv))
    guide_hits.sort(key=lambda x: x[:4], reverse=True)
    if not any(SYMPTOMS[k].get("rx") for k in keys):          # OTC complaint -> drop prescription drugs if there are enough OTC ones
        otc = [h for h in guide_hits if h[1] == 0]
        if len(otc) >= 2: guide_hits = otc
    for r in INVENTORY:
        sc = sum(_score(r["Primary Indication"], SYMPTOMS[k]["terms"]) for k in keys)
        if sc <= 0: continue
        if child and not re.search(r"child|pediatric|kid|children|baby", (r["Primary Indication"] + r["Trade Name"]).lower()):
            # inventory has no pediatric column -> for a child, accept only drugs that the guide marks as child-safe
            gg = next((g for g in GUIDE if _first(g["name"]) == _first(r["Trade Name"])), None)
            if not (gg and child_ok(gg["pediatric"])): continue
        avail = 0 if r["Availability Status"] == "Out of Stock" else 1
        inv_hits.append((sc, -int(r["Prescription Required"].strip().lower() == "yes"), avail, -len(inv_hits), r))
    inv_hits.sort(key=lambda x: x[:4], reverse=True)
    if not any(SYMPTOMS[k].get("rx") for k in keys):
        otc = [h for h in inv_hits if h[1] == 0]
        if len(otc) >= 1: inv_hits = otc
    return guide_hits[:top_n], inv_hits[:top_n]

# ---------- 6) Turning the matches into "items" (also what the chat remembers) ----------
def _price(v):
    m = re.search(r"\d+(?:\.\d+)?", str(v))
    return float(m.group(0)) if m else 0.0

def _is_rx(inv):
    return inv["Prescription Required"].strip().lower() == "yes"

def _stock_text(inv):
    return f"{inv['Availability Status']} ({inv['Stock Quantity']} units) - {inv['Location / Shelf']}"

def build_items(info, top_n=3):
    # one plain dict per recommended drug (guide drugs first, then inventory-only drugs)
    guide_hits, inv_hits = recommend(info, top_n)
    items, seen = [], set()
    for *_, g, inv in guide_hits:
        seen.add(_first(g["name"]))
        items.append({"source": "guide", "name": g["name"], "ingredient": g["ingredient"], "strength": "",
                      "price": _price(g["price"]), "dose": g["dose"], "pediatric": g["pediatric"],
                      "stock": _stock_text(inv) if inv else "",
                      "rx": _is_rx(inv) if inv else bool(RX_INGREDIENTS.search(g["ingredient"]))})
    for *_, r in inv_hits:
        if _first(r["Trade Name"]) in seen:        # already listed (with its stock) from the guide
            continue
        items.append({"source": "inventory", "name": r["Trade Name"], "ingredient": r["Active Ingredient"],
                      "strength": r["Strength"], "price": _price(r["Price (EGP)"]), "dose": "", "pediatric": "",
                      "stock": _stock_text(r), "rx": _is_rx(r)})
    return items

def _available(items):
    ok = [x for x in items if "out of stock" not in x["stock"].lower()]
    return ok or items

def pick_by_price(items, rank):
    # the cheapest / most expensive drug of a list (out-of-stock drugs are skipped when others exist)
    pool = _available(items)
    return min(pool, key=lambda x: x["price"]) if rank == "cheapest" else max(pool, key=lambda x: x["price"])

def items_context(items):
    # plain-text version of a list (used as 'retrieved_data' for the report/tests)
    return "\n".join(f"{x['name']} | {x['ingredient']} {x['strength']} | {x['price']:g} EGP | {x['dose']} | {x['pediatric']} | {x['stock']}"
                     for x in items)

# ---------- 7) Writing the answer (fixed templates, no LLM -> no hallucination) ----------
def _symptom_names(keys):
    return " + ".join(SYMPTOMS[k]["en"] for k in keys)

def _fmt_item(i, it, details=True):
    line = f"{i}. {it['name']} ({it['ingredient']})" + (f" {it['strength']}" if it["strength"] else "") + f" - {it['price']:g} EGP"
    if details and it["dose"]:
        line += f" | Dosage: {it['dose']}"
    if details and it["pediatric"]:
        line += f" | Children: {it['pediatric']}"
    if it["stock"]:
        line += f" | Inventory: {it['stock']}"
    if it["rx"]:
        line += " | Prescription required"
    return line

def format_two_drug_summary(shown):
    # "summarize" after a list -> only the top 2 drugs, one short line each
    L = [f"Summary - top {min(2, len(shown))} option{'s' if len(shown) > 1 else ''}:"]
    L += [_fmt_item(i, it, details=False) for i, it in enumerate(shown[:2], 1)]
    return "\n".join(L)

def format_rank(info, shown, pool, from_history):
    word = "cheapest" if info["rank"] == "cheapest" else "most expensive"
    where = "from the list above" if from_history else f"for ({_symptom_names(info['symptoms'])})" + (" in a child" if info["child"] else "")
    pick = shown[0]
    L = [f"The {word} option {where} is:", _fmt_item(1, pick)]
    if len(pool) > 1:
        skipped = len(pool) - len(_available(pool))
        L.append(f"(I compared {len(pool)} options" + (f"; {skipped} out-of-stock option(s) were skipped" if skipped else "") + ".)")
    if pick["rx"]:
        L.append("Note: this is a prescription medicine - a doctor must decide the right treatment.")
    if info["child"]:
        L.append("For children the dose depends on age and weight - please confirm with a pharmacist or pediatrician before giving any medicine.")
    L.append("(This is not a substitute for medical advice.)")
    return "\n".join(L)

def format_recommendation(info, shown, pool):
    keys, child = info["symptoms"], info["child"]
    if info["self_harm"]:
        return ("I'm really sorry you're going through this - you deserve real support right now. Please reach out to someone you trust "
                "or contact local emergency services (in Egypt: ambulance 123) or go to the nearest emergency room. I'm here to talk if you want to.")
    if info["red_flag"]:
        return ("⚠️ The symptoms you describe may be serious. Please go to the nearest emergency department or call emergency services "
                "right now, and do not self-medicate.")
    names = _symptom_names(keys)
    if not shown:
        return f"I couldn't find a suitable drug for ({names})" + (" for a child" if child else "") + " in my files. Please ask a pharmacist or doctor."
    if info["rank"]:
        return format_rank(info, shown, pool, from_history=False)

    L = [f"Get well soon! For ({names})" + (" in a child" if child else "") + ", these are the best matches in the medical guide and the pharmacy inventory:"]
    n = 0
    for title, source in (("From the medical guide:", "guide"), ("From the pharmacy inventory:", "inventory")):
        part = [x for x in shown if x["source"] == source]
        if part:
            L.append("\n" + title)
            for it in part:
                n += 1
                L.append(_fmt_item(n, it))
    if any(SYMPTOMS[k].get("rx") for k in keys):
        L.append("\nNote: these are prescription medicines - a doctor must decide the right treatment.")
    if child:
        L.append("\nFor children the dose depends on age and weight - please confirm with a pharmacist or pediatrician before giving any medicine.")
    L.append("\nIf symptoms get worse or last more than 3 days, see a doctor. (This is not a substitute for medical advice.)")
    return "\n".join(L)

# ---------- 8) Chat memory ----------
class ChatSession:
    """Keeps the chat history between turns and feeds it back into the workflow.
    - last_question / last_answer : for follow-ups like "what is the price of it?" and "summarize that"
    - pool  : every drug of the last recommendation (what "get the cheapest" compares)
    - shown : the drugs displayed last time (what "summarize" shortens to 2)
    """
    def __init__(self, app, vector_store):
        self.app, self.vector_store = app, vector_store
        self.last_question = self.last_answer = ""
        self.pool, self.shown = [], []

    def reset(self):
        self.last_question = self.last_answer = ""
        self.pool, self.shown = [], []

    def ask(self, task):
        state = {"task": task, "vector_store": self.vector_store, "retrieved_data": "", "processed_summary": "",
                 "final_output_path": "", "log": [],
                 "last_question": self.last_question, "last_answer": self.last_answer,
                 "last_pool": self.pool, "last_shown": self.shown}
        result = self.app.invoke(state)
        mode, answer = result.get("mode"), result["processed_summary"]
        if mode == "recommend":                       # a new list replaces the old one
            self.pool, self.shown = result.get("pool", []), result.get("shown", [])
            self.last_question, self.last_answer = task, answer
        elif mode == "rank":                          # same candidates, the displayed answer is the picked drug
            self.shown = result.get("shown", [])
            self.last_answer = answer
        elif mode in ("summarize_list", "summarize"):
            self.last_answer = answer
        elif mode in ("qa", "no_info"):               # a plain answer: the old list is no longer "the last answer"
            self.pool, self.shown = [], []
            self.last_question, self.last_answer = task, answer
        # smalltalk / nothing / nothing_to_rank: history stays as it was
        self.result = result
        return answer

