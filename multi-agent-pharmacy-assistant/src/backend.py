def clean_inventory_csv(csv_path, out_path="inventory_clean.csv"):
    # The sheet has blank/title rows above the real header + an empty first column,
    # so CSVLoader would read garbage. This keeps only the real table.
    raw = pd.read_csv(csv_path, header=None, dtype=str, keep_default_na=False)
    hdr = raw.index[raw.apply(lambda r: "Drug ID" in r.values, axis=1)][0]
    df = raw.iloc[hdr + 1:].copy()
    df.columns = [c.strip() for c in raw.iloc[hdr]]
    df = df.loc[:, [c for c in df.columns if c]]
    df = df[df["Drug ID"].str.startswith("DRUG")]
    df.to_csv(out_path, index=False)
    return out_path

def split_pdf_by_drug(pdf_path):
    # The guide is a TABLE of 120 numbered drugs ("1. Panadol Advance", "2. Cetal Tablets", ...)
    # -> one chunk per drug (keeps name + ingredient + price + dosage + pediatric safety together)
    text = "\n".join(p.page_content for p in PyPDFLoader(pdf_path).load())
    # drop everything after the disclaimer, page footers, section titles and the repeated table header
    text = re.split(r"Important Medical Disclaimer", text)[0]
    text = re.sub(r"^.*Comprehensive Pharmacy AI Knowledge Base.*$", "", text, flags=re.M)
    text = re.sub(r"^Section \d+:.*$", "", text, flags=re.M)
    text = re.sub(r"^Trade & Active\s*\nIngredient\s*\nEst\.\s*\nPrice.*$", "", text, flags=re.M)
    # a new drug starts with "<1-3 digits>. <Capital letter>" at the beginning of a line
    parts = re.split(r"\n(?=\d{1,3}\.\s+[A-Z])", text)
    docs = []
    for p in parts:
        p = p.strip()
        if re.match(r"\d{1,3}\.\s", p):
            docs.append(Document(page_content=p, metadata={"source": pdf_path}))
    return docs

