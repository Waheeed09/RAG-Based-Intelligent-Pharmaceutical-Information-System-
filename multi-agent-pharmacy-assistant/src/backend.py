# Real external API: openFDA drug labels (free, no key). Looks up the drug named in the question / retrieved text.
FDA_NAMES = {"paracetamol": "acetaminophen", "ibuprofen": "ibuprofen", "diclofenac": "diclofenac",
             "cetirizine": "cetirizine", "omeprazole": "omeprazole", "azithromycin": "azithromycin",
             "amoxicillin": "amoxicillin", "pseudoephedrine": "pseudoephedrine", "metformin": "metformin",
             "atorvastatin": "atorvastatin", "loratadine": "loratadine", "salbutamol": "albuterol"}

def fetch_fda_label(context: str) -> str:
    low = context.lower()
    found = [(low.index(n), n) for n in FDA_NAMES if n in low]
    if not found:
        return "No drug name recognised for the FDA lookup."
    name = FDA_NAMES[min(found)[1]]
    try:
        r = requests.get("https://api.fda.gov/drug/label.json",
                         params={"search": f'openfda.generic_name:"{name}"', "limit": 1}, timeout=8)
        res = r.json()["results"][0]
        warn = (res.get("warnings") or res.get("boxed_warning") or [""])[0][:300]
        return f"openFDA label for {name}: {warn}"
    except Exception as e:
        return f"openFDA API unavailable ({type(e).__name__})."

