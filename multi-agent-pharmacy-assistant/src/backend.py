def keywords(text):
    # Distinctive words of a text (plural 's' removed) - mainly drug names / conditions
    out = set()
    for w in re.findall(r"[a-z0-9]+", text.lower()):
        if len(w) >= 4 and w not in STOP:
            out.add(w[:-1] if w.endswith("s") and len(w) > 4 else w)
    return out

def expand_query(task, last_question):
    # Follow-up such as "what is the price of it?" -> add the previous question so the search knows the drug
    if last_question and FOLLOW_UP.search(task):
        return f"{last_question} {task}"
    return task

def rerank_docs(task, docs, top_n=2):
    # Keep the chunks that contain the distinctive words of the question (e.g. the drug name).
    # Also returns `matched`: False means nothing retrieved is really about the question.
    words = keywords(task)
    texts = [d.page_content.lower() for d in docs]
    useful = [w for w in words if sum(w in t for t in texts) <= len(docs) / 2]
    score = lambda i: sum(w in texts[i] for w in useful)
    order = sorted(range(len(docs)), key=lambda i: (-score(i), i))[:top_n]
    return [docs[i] for i in order], any(score(i) > 0 for i in order)

def retrieve_docs(vector_store, query, k=8, top_n=2):
    return rerank_docs(query, vector_store.similarity_search(query, k=k), top_n=top_n)

def ask_llm(system, user):
    # TinyLlama chat format
    prompt = f"<|system|>\n{system}</s>\n<|user|>\n{user}</s>\n<|assistant|>\n"
    out = str(local_llm.invoke(prompt))
    if "<|" in out:
        out = out.split("<|")[0]
    return out.strip()

def _stems(text):
    return {t[:5] for t in re.findall(r"[a-z0-9]+", text.lower()) if len(t) >= 4 and t not in COMMON}

def is_grounded(answer, context, min_ratio=0.6):
    # Is the answer usable? (not empty, not "I don't know", no foreign drug, words come from the context)
    if len(answer.strip()) < 3:
        return False
    low = answer.lower()
    if re.search(r"i don'?t know|i do not know|not (?:provided|mentioned)|cannot answer", low):
        return False
    if (set(re.findall(r"[a-z]+", low)) & DRUG_TERMS) - set(re.findall(r"[a-z]+", context.lower())):
        return False
    a, c = _stems(answer), _stems(context)
    return not a or len(a & c) / len(a) >= min_ratio

def extractive_answer(docs, max_chars=700):
    # Safe fallback: show the retrieved facts directly (no LLM involved)
    parts = []
    for d in docs[:2]:
        lines = [l.strip() for l in d.page_content.splitlines() if l.strip()]
        is_pdf = str(d.metadata.get("source", "")).lower().endswith(".pdf")
        parts.append((" " if is_pdf else "; ").join(lines))
    text = "Here is what I found:\n\n" + "\n\n".join(parts)
    return text if len(text) <= max_chars else text[:max_chars].rsplit(" ", 1)[0] + "..."

def summarize_text(text):
    # Up to 2 LLM tries, then a deterministic fallback (first two sentences)
    for system in ("Summarize the text in 1-2 short sentences. Use only facts from the text.",
                   "Rewrite the text as one short sentence. Use only the words and facts in the text."):
        out = ask_llm(system, text)
        if is_grounded(out, text, 0.7) and len(out) < len(text):
            return out
    return " ".join(re.split(r"(?<=[.!?])\s+", text.strip())[:2])

QA_SYSTEM = ("You are a pharmacy assistant. Answer the question using ONLY the context. "
             "Talk only about the drug in the question. Never mention other drugs. "
             "If the answer is not in the context, say: I don't know. Keep the answer to 1-3 sentences.")

def answer_question(state):
    task = state["task"]

    # Try 1: the best 2 chunks
    context = state["context"]
    out = ask_llm(QA_SYSTEM, f"Context:\n{context}\n\nQuestion: {task}")
    if is_grounded(out, context):
        state["log"].append("Processing: answered on try 1.")
        return out

    # Try 2: expand the search (more candidates, 3 chunks) and ask again
    query = expand_query(task, state.get("last_question", ""))
    docs, _ = retrieve_docs(state["vector_store"], query, k=12, top_n=3)
    context2 = "\n\n".join(d.page_content for d in docs)
    if "fda" in task.lower():
        context2 += "\n\n" + state["retrieved_data"].split("EXTERNAL API CONTEXT:\n")[-1]
    out = ask_llm(QA_SYSTEM + " Answer briefly.", f"Context:\n{context2}\n\nQuestion: {task}")
    if is_grounded(out, context2):
        state["log"].append("Processing: answered on try 2 (expanded search).")
        return out

    # Fallback: show the retrieved facts directly
    state["log"].append("Processing: LLM answer rejected twice, used extractive fallback.")
    return extractive_answer(state["docs"] or docs)

